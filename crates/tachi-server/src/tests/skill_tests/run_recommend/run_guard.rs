#[tokio::test]
async fn document_skill_run_returns_verbatim_content_without_simulation_marker() {
    let server = make_server();
    const DOCUMENT_CONTENT: &str = "# Workflow\n\n1. Read the repo.\n2. Run the tests.";
    server
        .hub_register(Parameters(HubRegisterParams {
            id: "skill:document-workflow".to_string(),
            cap_type: "skill".to_string(),
            name: "document-workflow".to_string(),
            description: "workflow document skill".to_string(),
            definition: json!({
                "execution": "document",
                "prompt": "An LLM path would not return the content verbatim.",
                "content": DOCUMENT_CONTENT,
                "policy": {"visibility": "listed"},
                "inputSchema": {"type": "object"}
            })
            .to_string(),
            version: 1,
            scope: "global".to_string(),
        }))
        .await
        .expect("hub_register document skill");

    let response = server
        .tachi_skill(Parameters(tachi_skill_run_params(
            "skill:document-workflow",
            json!({"input": "fixture"}),
        )))
        .await
        .expect("document skill run should succeed");
    let envelope: Value = serde_json::from_str(&response).expect("document response json");

    assert_eq!(envelope["status"], json!("completed"));
    assert_eq!(envelope["action"], json!("run"));
    assert_eq!(envelope["skill_id"], json!("skill:document-workflow"));
    assert_eq!(envelope["execution"], json!("document"));
    assert_eq!(envelope["simulated"], json!(false));
    assert_eq!(envelope["output"], json!(DOCUMENT_CONTENT));
    assert!(!envelope["output"]
        .as_str()
        .expect("output text")
        .starts_with(crate::hub_ops::SIMULATED_SKILL_OUTPUT_MARKER));
    assert!(envelope["instruction"]
        .as_str()
        .is_some_and(|instruction| !instruction.is_empty()));
    assert!(envelope.get("warning").is_none());
}

